merged_table_code=(
    """
    WITH weighted_deprivation AS (
    SELECT lookup.ICB26CD, lookup.ICB26NM,
    SUM((depr."Index of Multiple Deprivation (IMD) Score"*depr."Total population: mid 2022"))/Sum(depr."Total population: mid 2022") AS weighted_deprivation_score,
    SUM((depr."Income Score (rate)"*depr."Total population: mid 2022"))/Sum(depr."Total population: mid 2022") AS weighted_income_score,
    SUM((depr."Employment Score (rate)"*depr."Working age population 18-66 (for use with Employment Deprivation Domain): mid 2022"))/Sum(depr."Working age population 18-66 (for use with Employment Deprivation Domain): mid 2022") AS weighted_employment_score,
    SUM((depr."Education, Skills and Training Score"*depr."Total population: mid 2022"))/Sum(depr."Total population: mid 2022") AS weighted_education_score
    FROM indices_of_deprivation_scores AS depr
    JOIN lookup_data AS lookup
    ON depr."LSOA code (2021)" = lookup.LSOA21CD
    GROUP BY lookup.ICB26CD, lookup.ICB26NM

    )

    SELECT w_dep.ICB26CD, w_dep.ICB26NM, w_dep.weighted_deprivation_score, w_dep.weighted_income_score, w_dep.weighted_employment_score, w_dep.weighted_education_score, prev."Prevalence (%)"
    FROM prevalence_data AS prev
    LEFT JOIN weighted_deprivation as w_dep
    ON prev."ICB ONS code"=w_dep.ICB26CD

""")


merged_table=pd.read_sql(merged_table_code,con)



#cleaning
merged_table=merged_table.dropna(subset=["ICB26CD"])
namedict={"weighted_deprivation_score":"Deprivation Score","weighted_income_score":"Income Score", "weighted_employment_score":"Employment Score", "weighted_education_score":"Education Score", "Prevalence (%)":"Percentage Prevalance of Depression (%)"}
